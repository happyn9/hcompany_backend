"""H-Learning Mission 0.1 — `scripts/lessonprogress_uniqueness.py` (progression unique par élève et leçon).

La contrainte existe déjà dans la migration d'origine a3c8e5d17b42 ; le script ne sert qu'aux bases créées sans elle.
Non destructif : les doublons sont FUSIONNÉS (meilleure progression gardée) et COPIÉS dans `lessonprogress_dup_archive`.
SQLite toujours ; PostgreSQL jetable si HFOOD_TEST_PG_URL (mêmes garde-fous que les tests HFood, schéma isolé).
Ne modifie jamais os.environ : l'URL est passée au sous-processus alembic."""
import os
import subprocess
import sys
import tempfile
from datetime import datetime

import pytest
import sqlalchemy as sa

from tests import pg_safety as safety

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRE = "a1d5c8e2f4b7"  # tête Alembic « ancienne » : la table lessonprogress et sa contrainte y existent déjà
sys.path.insert(0, os.path.join(BACKEND, "scripts"))
import lessonprogress_uniqueness as fix  # noqa: E402
PG = os.environ.get(safety.ENV_URL, "").strip()
TARGET = None
if PG:
    _env = dict(os.environ)
    TARGET = safety.check_test_url(PG, environ=_env)
    safety.require_confirmation(TARGET, environ=_env)
T1, T2, T3 = datetime(2026, 1, 1), datetime(2026, 1, 2), datetime(2026, 1, 3)


class Db:
    def __init__(self, kind):
        self.pg, self.tmp, self.schema, self.created = kind == "pg", None, None, False
        if self.pg:
            self.schema = safety.new_schema_name()
            self.url = safety.scoped_url(TARGET, self.schema)
        else:
            self.tmp = tempfile.mkdtemp(prefix="hl_mig_")
            self.url = f"sqlite:///{self.tmp}/mig.db"
        self.engine = sa.create_engine(self.url)

    def create(self):
        if self.pg:
            safety.create_schema(self.engine, self.schema)
            self.created = True

    def ok(self, *args):
        env = {**os.environ, "DATABASE_URL": self.url, "PYTHONDONTWRITEBYTECODE": "1"}
        r = subprocess.run([sys.executable, "-B", "-m", "alembic", *args], cwd=BACKEND, env=env, capture_output=True, text=True)
        assert r.returncode == 0, r.stderr[-1500:]

    def q(self, sql, **kw):
        with self.engine.begin() as cx:
            res = cx.execute(sa.text(sql), kw)
            return res.fetchall() if res.returns_rows else []

    def indexes(self):
        self.engine.dispose()
        return {i["name"] for i in sa.inspect(self.engine).get_indexes("lessonprogress")}

    def tables(self):
        self.engine.dispose()
        return set(sa.inspect(self.engine).get_table_names())

    def _insert(self, obj, table):
        """INSERT en SQL brut limité aux colonnes présentes dans la base à cette révision (pas de cast d'enum de l'ORM)."""
        self.engine.dispose()
        cols = {c["name"] for c in sa.inspect(self.engine).get_columns(table)}
        vals = {}
        for c in cols - {"id"}:
            v = getattr(obj, c, None)
            if v is not None:
                vals[c] = getattr(v, "value", v)
        sql = f'INSERT INTO "{table}" ({", ".join(vals)}) VALUES ({", ".join(":" + k for k in vals)}) RETURNING id'
        with self.engine.begin() as cx:
            return cx.execute(sa.text(sql), vals).scalar()

    def seed(self):
        from app.models import Course, Lesson, User
        self.u = [self._insert(User(email=f"{k}@m.io", full_name=k), "user") for k in ("a", "b")]
        cid = self._insert(Course(title="C", level="x", description="d", is_published=True), "course")
        self.l = [self._insert(Lesson(course_id=cid, title=f"L{i}", youtube_id=f"y{i}", is_published=True), "lesson") for i in range(2)]

    def drift(self):
        """Simule une base dont la table a été créée SANS la contrainte (ancien create_all) : on la recrée sans unicité."""
        self.q("DROP TABLE lessonprogress")
        self.q("CREATE TABLE lessonprogress (id INTEGER PRIMARY KEY " + ("" if not self.pg else "GENERATED BY DEFAULT AS IDENTITY") +
               ", user_id INTEGER NOT NULL REFERENCES \"user\" (id), lesson_id INTEGER NOT NULL REFERENCES lesson (id), "
               "completed BOOLEAN NOT NULL, position_seconds INTEGER NOT NULL, updated_at TIMESTAMP NOT NULL)")

    def prog(self, user, lesson, completed, pos, at):
        self.q("INSERT INTO lessonprogress (user_id, lesson_id, completed, position_seconds, updated_at) "
               "VALUES (:u, :l, :c, :p, :t)", u=user, l=lesson, c=completed, p=pos, t=at)

    def close(self):
        try:
            self.engine.dispose()
            if self.pg and self.created:
                e = sa.create_engine(safety.scoped_url(TARGET, self.schema))
                try:
                    safety.drop_schema(e, self.schema)
                finally:
                    e.dispose()
        finally:
            if self.tmp:
                import shutil
                shutil.rmtree(self.tmp, ignore_errors=True)


@pytest.fixture(params=["sqlite", pytest.param("pg", marks=pytest.mark.skipif(not PG, reason="nécessite HFOOD_TEST_PG_URL (PostgreSQL de test)"))])
def db(request):
    d = Db(request.param)
    try:
        d.create()
        d.ok("upgrade", PRE)
        d.seed()
        yield d
    finally:
        d.close()


def _status(d):
    with d.engine.connect() as c:
        return fix.status(c)


def _apply(d):
    with d.engine.begin() as c:
        return fix.repair(c)


def test_normal_database_already_has_the_constraint_and_script_is_a_noop(db):
    """Base issue des migrations : la contrainte d'origine (a3c8e5d17b42) existe déjà ; le script ne change rien."""
    db.prog(db.u[0], db.l[0], False, 1, T1)
    with pytest.raises(sa.exc.IntegrityError):
        db.prog(db.u[0], db.l[0], False, 2, T2)
    assert _status(db) == {"table": True, "unique": True, "duplicate_groups": 0}
    assert _apply(db)["changed"] is False
    assert "lessonprogress_dup_archive" not in db.tables() and db.q("SELECT count(*) FROM lessonprogress")[0][0] == 1


def _seed_duplicates(d):
    d.drift()
    # (élève a, leçon 0) : 3 lignes ; (a, leçon 1) et (b, leçon 0) : une seule ligne chacune
    d.prog(d.u[0], d.l[0], False, 30, T1)
    d.prog(d.u[0], d.l[0], True, 50, T2)
    d.prog(d.u[0], d.l[0], False, 70, T3)
    d.prog(d.u[0], d.l[1], False, 11, T1)
    d.prog(d.u[1], d.l[0], True, 99, T2)


def test_dry_run_reports_without_changing_anything(db):
    _seed_duplicates(db)
    assert _status(db) == {"table": True, "unique": False, "duplicate_groups": 1}
    assert db.q("SELECT count(*) FROM lessonprogress")[0][0] == 5 and "lessonprogress_dup_archive" not in db.tables()


def test_duplicates_are_merged_archived_and_index_created(db):
    _seed_duplicates(db)
    before = db.q("SELECT count(*) FROM lessonprogress")[0][0]
    res = _apply(db)
    assert res == {"changed": True, "groups_merged": 1, "rows_archived": 2}
    assert "uq_lessonprogress_user_lesson" in db.indexes()
    rows = db.q("SELECT user_id, lesson_id, completed, position_seconds FROM lessonprogress ORDER BY user_id, lesson_id")
    assert len(rows) == 3
    merged = [r for r in rows if (r[0], r[1]) == (db.u[0], db.l[0])]
    assert len(merged) == 1 and bool(merged[0][2]) is True and merged[0][3] == 70  # terminée si l'une l'était ; position la plus récente
    assert [r for r in rows if (r[0], r[1]) == (db.u[0], db.l[1])][0][3] == 11      # lignes sans doublon intactes
    assert [r for r in rows if (r[0], r[1]) == (db.u[1], db.l[0])][0][3] == 99
    arch = db.q("SELECT orig_id, kept_id FROM lessonprogress_dup_archive ORDER BY orig_id")
    assert len(arch) == 2 and len({a[1] for a in arch}) == 1                        # 2 lignes copiées, rattachées à la ligne conservée
    assert before == len(rows) + len(arch)                                           # rien n'a disparu : conservées + archivées = avant
    with pytest.raises(sa.exc.IntegrityError):
        db.prog(db.u[0], db.l[0], False, 1, T3)
    assert _status(db) == {"table": True, "unique": True, "duplicate_groups": 0}


def test_without_duplicates_creates_only_the_index_and_no_archive(db):
    db.drift()
    db.prog(db.u[0], db.l[0], True, 5, T1)
    db.prog(db.u[1], db.l[0], False, 6, T2)
    assert _apply(db) == {"changed": True, "groups_merged": 0, "rows_archived": 0}
    assert "uq_lessonprogress_user_lesson" in db.indexes() and "lessonprogress_dup_archive" not in db.tables()
    assert db.q("SELECT count(*) FROM lessonprogress")[0][0] == 2
    assert db.q("SELECT count(*) FROM course")[0][0] == 1 and db.q("SELECT count(*) FROM lesson")[0][0] == 2


def test_rerun_is_a_noop(db):
    _seed_duplicates(db)
    _apply(db)
    assert _apply(db)["changed"] is False
    assert db.q("SELECT count(*) FROM lessonprogress")[0][0] == 3 and db.q("SELECT count(*) FROM lessonprogress_dup_archive")[0][0] == 2
