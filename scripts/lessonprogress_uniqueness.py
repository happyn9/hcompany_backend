#!/usr/bin/env python
"""H-Learning : vérifie / garantit « une seule progression par (élève, leçon) » — NON destructif, sans effet par défaut.

Pourquoi un script et non une révision Alembic : la contrainte `uq_lessonprogress_user_lesson` existe DÉJÀ dans la
migration d'origine (a3c8e5d17b42), donc toute base issue des migrations l'a. Ce script ne sert que de filet pour une base
dont la table aurait été créée sans elle (ancien `create_all` depuis des modèles qui ne la déclaraient pas). Une nouvelle
révision ajouterait une tête Alembic et casserait l'invariant de topologie vérifié par les tests HFood.

Usage (rien n'est lu dans l'environnement ni dans un .env : l'URL est passée explicitement) :
    python scripts/lessonprogress_uniqueness.py --url postgresql://...            # diagnostic seul (lecture)
    python scripts/lessonprogress_uniqueness.py --url postgresql://... --apply    # fusionne les doublons puis crée l'index

Avec --apply, dans UNE transaction : pour chaque couple en double, la ligne de plus petit id reçoit la meilleure progression
(terminée si l'une l'est ; position et date de la plus récente) ; chaque ligne en trop est COPIÉE dans
`lessonprogress_dup_archive` avant d'être retirée ; puis l'index unique est créé. Rejouable sans effet.
Ne jamais lancer --apply sur une base de production sans sauvegarde préalable et validation humaine."""
import argparse
import sys
from datetime import datetime

import sqlalchemy as sa

INDEX = "uq_lessonprogress_user_lesson"
ARCHIVE = "lessonprogress_dup_archive"
COLS = {"user_id", "lesson_id"}


def has_unique(insp) -> bool:
    if any(i.get("unique") and set(i["column_names"]) == COLS for i in insp.get_indexes("lessonprogress")):
        return True
    return any(set(u["column_names"]) == COLS for u in insp.get_unique_constraints("lessonprogress"))


def duplicate_groups(conn):
    return conn.execute(sa.text(
        "SELECT user_id, lesson_id, COUNT(*) FROM lessonprogress GROUP BY user_id, lesson_id HAVING COUNT(*) > 1"
    )).fetchall()


def status(conn) -> dict:
    insp = sa.inspect(conn)
    if not insp.has_table("lessonprogress"):
        return {"table": False}
    return {"table": True, "unique": has_unique(insp), "duplicate_groups": len(duplicate_groups(conn))}


def repair(conn) -> dict:
    """À appeler dans une transaction (engine.begin()). Renvoie un compte rendu ; ne fait rien si tout est en ordre."""
    insp = sa.inspect(conn)
    if not insp.has_table("lessonprogress"):
        return {"changed": False, "reason": "table absente"}
    if has_unique(insp):
        return {"changed": False, "reason": "contrainte déjà présente"}
    groups = duplicate_groups(conn)
    archived = 0
    if groups and not insp.has_table(ARCHIVE):
        conn.execute(sa.text(
            f"CREATE TABLE {ARCHIVE} (id INTEGER PRIMARY KEY {'GENERATED BY DEFAULT AS IDENTITY' if conn.dialect.name == 'postgresql' else ''}, "
            "kept_id INTEGER NOT NULL, orig_id INTEGER NOT NULL, user_id INTEGER NOT NULL, lesson_id INTEGER NOT NULL, "
            "completed BOOLEAN NOT NULL, position_seconds INTEGER NOT NULL, updated_at TIMESTAMP, archived_at TIMESTAMP NOT NULL)"
        ))
    now = datetime.utcnow()
    for user_id, lesson_id, _n in groups:
        rows = conn.execute(sa.text(
            "SELECT id, completed, position_seconds, updated_at FROM lessonprogress WHERE user_id = :u AND lesson_id = :l ORDER BY id"
        ), {"u": user_id, "l": lesson_id}).fetchall()
        keep = rows[0]
        newest = max(rows, key=lambda r: (str(r.updated_at or ""), r.id))
        latest = max((r.updated_at for r in rows if r.updated_at is not None), default=None, key=str)
        conn.execute(sa.text("UPDATE lessonprogress SET completed = :c, position_seconds = :p, updated_at = :t WHERE id = :i"),
                     {"c": any(bool(r.completed) for r in rows), "p": newest.position_seconds, "t": latest, "i": keep.id})
        for r in rows[1:]:
            conn.execute(sa.text(
                f"INSERT INTO {ARCHIVE} (kept_id, orig_id, user_id, lesson_id, completed, position_seconds, updated_at, archived_at) "
                "VALUES (:k, :o, :u, :l, :c, :p, :t, :a)"),
                {"k": keep.id, "o": r.id, "u": user_id, "l": lesson_id, "c": bool(r.completed),
                 "p": r.position_seconds, "t": r.updated_at, "a": now})
            conn.execute(sa.text("DELETE FROM lessonprogress WHERE id = :i"), {"i": r.id})
            archived += 1
    conn.execute(sa.text(f"CREATE UNIQUE INDEX {INDEX} ON lessonprogress (user_id, lesson_id)"))
    return {"changed": True, "groups_merged": len(groups), "rows_archived": archived}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--url", required=True, help="URL SQLAlchemy de la base (jamais lue depuis l'environnement)")
    ap.add_argument("--apply", action="store_true", help="applique la correction (sinon : diagnostic en lecture seule)")
    args = ap.parse_args(argv)
    engine = sa.create_engine(args.url)
    with engine.connect() as c:
        print("état :", status(c))
    if args.apply:
        with engine.begin() as c:
            print("correction :", repair(c))
    return 0


if __name__ == "__main__":
    sys.exit(main())
